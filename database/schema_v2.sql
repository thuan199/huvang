-- 17. Tự động tạo profile khi đăng ký tài khoản
-- =========================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.profiles (
        id,
        email,
        full_name,
        avatar_url
    )
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(
            NEW.raw_user_meta_data ->> 'full_name',
            NEW.raw_user_meta_data ->> 'name'
        ),
        NEW.raw_user_meta_data ->> 'avatar_url'
    )
    ON CONFLICT (id) DO NOTHING;

    RETURN NEW;
END;
$$;


CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();


-- =========================================================
-- 18. View tổng hợp số vàng đang sở hữu
-- BUY cộng vào, SELL trừ ra
-- =========================================================

CREATE OR REPLACE VIEW public.user_gold_holdings
WITH (security_invoker = true)
AS
SELECT
    gt.user_id,
    gt.gold_type_id,

    COALESCE(gtype.code, 'UNCLASSIFIED') AS gold_type_code,
    COALESCE(gtype.name, gt.gold_name) AS gold_type_name,

    SUM(
        CASE
            WHEN gt.transaction_type = 'BUY'
                THEN gt.quantity_chi
            WHEN gt.transaction_type = 'SELL'
                THEN -gt.quantity_chi
            ELSE 0
        END
    ) AS quantity_chi,

    SUM(
        CASE
            WHEN gt.transaction_type = 'BUY'
                THEN gt.total_amount
            WHEN gt.transaction_type = 'SELL'
                THEN -gt.total_amount
            ELSE 0
        END
    ) AS net_invested_amount,

    MAX(gt.transaction_date) AS latest_transaction_date

FROM public.gold_transactions gt

LEFT JOIN public.gold_types gtype
    ON gtype.id = gt.gold_type_id

GROUP BY
    gt.user_id,
    gt.gold_type_id,
    gtype.code,
    gtype.name,
    gt.gold_name

HAVING SUM(
    CASE
        WHEN gt.transaction_type = 'BUY'
            THEN gt.quantity_chi
        WHEN gt.transaction_type = 'SELL'
            THEN -gt.quantity_chi
        ELSE 0
    END
) <> 0;

COMMENT ON VIEW public.user_gold_holdings
IS 'Tổng hợp số lượng vàng hiện đang sở hữu từ lịch sử mua bán';

