    unit_price NUMERIC(18,2) NOT NULL,

    fee_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(18,2) NOT NULL,

    transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,

