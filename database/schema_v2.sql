CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =========================================================
-- 1. Danh mục nguồn cung cấp giá
-- =========================================================

CREATE TABLE public.gold_price_sources (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,

    website_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT gold_price_sources_code_key UNIQUE (code)
);

COMMENT ON TABLE public.gold_price_sources
IS 'Danh sách nguồn cung cấp giá vàng như PNJ, MI_HONG, SJC, DOJI';

COMMENT ON COLUMN public.gold_price_sources.code
IS 'Mã nguồn dùng trong chương trình, ví dụ PNJ, MI_HONG, SJC';


-- =========================================================
-- 2. Danh mục loại vàng chuẩn
-- Dùng để so sánh sản phẩm tương đương giữa nhiều nguồn
-- =========================================================

CREATE TABLE public.gold_types (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,

    purity NUMERIC(6,3),
    unit VARCHAR(30) NOT NULL DEFAULT 'chi',

    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT gold_types_code_key UNIQUE (code)
);

COMMENT ON TABLE public.gold_types
IS 'Danh mục loại vàng chuẩn dùng chung để so sánh giữa các nguồn';

COMMENT ON COLUMN public.gold_types.purity
IS 'Hàm lượng vàng, ví dụ 999.900 hoặc 750.000';


-- =========================================================
-- 3. Sản phẩm thực tế của từng nguồn
-- =========================================================

CREATE TABLE public.gold_source_products (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    source_id UUID NOT NULL,
    gold_type_id UUID,

    product_code VARCHAR(100) NOT NULL,
    product_name VARCHAR(255) NOT NULL,

    source_unit VARCHAR(30) NOT NULL DEFAULT 'chi',
    conversion_to_chi NUMERIC(12,6) NOT NULL DEFAULT 1,

    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT gold_source_products_source_fk
        FOREIGN KEY (source_id)
        REFERENCES public.gold_price_sources(id)
        ON DELETE CASCADE,

    CONSTRAINT gold_source_products_gold_type_fk
        FOREIGN KEY (gold_type_id)
        REFERENCES public.gold_types(id)
        ON DELETE SET NULL,

    CONSTRAINT gold_source_products_source_product_key
        UNIQUE (source_id, product_code)
);

COMMENT ON TABLE public.gold_source_products
IS 'Danh sách sản phẩm vàng cụ thể được công bố bởi từng nguồn';

COMMENT ON COLUMN public.gold_source_products.conversion_to_chi
IS 'Hệ số đổi đơn vị nguồn về chỉ; ví dụ 1 lượng = 10 chỉ';


-- =========================================================
-- 4. Giá mới nhất
-- Mỗi sản phẩm của mỗi nguồn chỉ có một dòng
-- =========================================================

CREATE TABLE public.gold_price_latest (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    source_product_id UUID NOT NULL,

    buy_price NUMERIC(18,2),
    sell_price NUMERIC(18,2),

    source_updated_at TIMESTAMPTZ,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    raw_data JSONB,

    CONSTRAINT gold_price_latest_product_fk
        FOREIGN KEY (source_product_id)
        REFERENCES public.gold_source_products(id)
        ON DELETE CASCADE,

    CONSTRAINT gold_price_latest_product_key
        UNIQUE (source_product_id),

    CONSTRAINT gold_price_latest_buy_price_check
        CHECK (buy_price IS NULL OR buy_price >= 0),

    CONSTRAINT gold_price_latest_sell_price_check
        CHECK (sell_price IS NULL OR sell_price >= 0)
);

COMMENT ON TABLE public.gold_price_latest
IS 'Lưu giá mua và giá bán mới nhất của từng sản phẩm';

COMMENT ON COLUMN public.gold_price_latest.raw_data
IS 'Dữ liệu gốc do website hoặc API nguồn trả về, dùng để kiểm tra lỗi';


